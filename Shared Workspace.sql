GRANT WRITE ON WORKSPACE GIT_INTEGRATION_DB.SHARED.TEAM_WS TO ROLE sysadmin;

-- 3. Check it exists
SHOW TERSE WORKSPACES IN SCHEMA GIT_INTEGRATION_DB.SHARED;

